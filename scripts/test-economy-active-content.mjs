import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { load } from './education-test-harness.mjs';
const worlds = load('src/lib/education.ts').educationWorlds;
const economy = worlds.find(world => world.id === 'economia');
assert.equal(economy.tracks.length, 7);
assert.deepEqual(economy.tracks.map(track => track.lessons.length), [7,0,0,0,0,0,0]);
assert.deepEqual(economy.tracks.flatMap(track => track.lessons).map(lesson => lesson.documentId), ['pib','inflacao','desemprego','crescimento','ciclos','demanda','consumo']);
assert.ok(economy.tracks.every(track => !track.internalTopics));
const archive = JSON.parse(readFileSync('docs/economy-empty-topics-archive.json','utf8'));
const removed = archive.tracks.flatMap(track => track.removedTopics);
assert.equal(removed.length, 68);
assert.ok(removed.every(lesson => !lesson.documentId && lesson.questions.length === 0));
const activeIDs = economy.tracks.flatMap(track => track.lessons.map(lesson => lesson.id));
const restoredIDs = ['economia-macro-topico-4', 'economia-macro-topico-5', 'economia-macro-topico-6', 'economia-macro-topico-7'];
for(const lesson of removed) assert.equal(activeIDs.includes(lesson.id), restoredIDs.includes(lesson.id));
assert.equal(economy.tracks.filter(track => track.reference).length, 6);
assert.ok(worlds.filter(world => world.id !== 'economia').every(world => world.tracks.length === 0));
console.log('PASS: seven parent areas preserved; seven topics with activities; topics 4 to 7 restored with content; remaining archived topics absent from active catalog.');
