import { readFileSync, writeFileSync } from 'node:fs';
import ts from 'typescript';
function load(file, deps = {}) {
  const exports = {};
  const code = ts.transpileModule(readFileSync(file, 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText;
  new Function('exports', 'require', code)(exports, name => {
    if (name === 'server-only') return {};
    if (!(name in deps)) throw new Error('Unexpected dependency: ' + name);
    return deps[name];
  });
  return exports;
}
const exports = load('src/lib/data.ts', { './education': load('src/lib/education.ts'), './legacy-data': load('src/lib/legacy-data.ts'), './legacy-achievements': load('src/lib/legacy-achievements.ts') });
const ids = new Set();
for (const world of exports.worlds) {
  for (const item of [world, ...world.tracks, ...world.tracks.flatMap(track => track.lessons)]) {
    if (!/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(item.id) || ids.has(item.id) || (!world.original && (/^m[1-7]-t\d+$/.test(item.id) || /^mundo-/.test(item.id))) || item.id === 'trilhas') throw new Error('Invalid or reused education ID: ' + item.id);
    ids.add(item.id);
  }
}
const catalog = exports.worlds.map(({ tracks, tasks, ...world }) => ({ ...world,
 tracks: tracks.map(track => ({ id: track.id, title: track.title, description: track.description, lessonIds: track.lessons.map(lesson => lesson.id) })),
 tasks: tasks.map(lesson => ({ id: lesson.id, title: lesson.title, questionCount: lesson.questions.length })),
}));
writeFileSync('src/lib/catalog.ts', '// Generated by npm run catalog:generate. No lesson text or answer keys.\nexport const worlds: { id: string; name: string; number: string; subtitle: string; description: string; color: string; icon: string; certificateTitle: string; original: boolean; prerequisiteWorldIds: string[]; tracks: { id: string; title: string; description: string; lessonIds: string[] }[]; tasks: { id: string; title: string; questionCount: number }[] }[] = ' + JSON.stringify(catalog, null, 2) + ';\n');
