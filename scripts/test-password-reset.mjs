import assert from 'node:assert/strict';
import { randomUUID, createHash } from 'node:crypto';
import { assertTestDatabase } from './test-safety.mjs';
export async function testPasswordReset({ prisma, base, post, current, mail, delivery, clearLimits, accounts }) {
  assertTestDatabase();
  const email = randomUUID() + '@example.test', password = 'Original secure password 123';
  const nextPassword = 'Replacement secure password 456';
  const hash = token => createHash('sha256').update(token).digest('hex');
  const waitFor = async predicate => {
    for (let i = 0; i < 300; i++) { if (await predicate()) return; await new Promise(r => setTimeout(r, 100)); }
    assert.fail('Background recovery work did not complete');
  };
  await clearLimits();
  assert.equal((await post('/api/session', { action: 'register', email, name: 'Recovery', password })).status, 202);
  const user = await prisma.user.findUniqueOrThrow({ where: { email } }); accounts.push(user.id);
  const login = secret => post('/api/session', { action: 'login', email, password: secret });
  const cookie = (await login(password)).headers.get('set-cookie').split(';')[0];
  const request = address => post('/api/auth/forgot-password', { email: address });
  const reset = (token, secret = nextPassword, confirmation = secret) => post('/api/auth/reset-password', { token, password: secret, confirmPassword: confirmation });
  const issue = async () => {
    await clearLimits(); const before = mail.length;
    const response = await request('  ' + email.toUpperCase() + '  ');
    assert.equal(response.status, 202);
    await waitFor(() => mail.length > before);
    const message = mail.at(-1);
    assert.equal(message.to[0], email);
    assert.equal(message.subject, 'Redefinição de senha - Politika');
    assert.ok(message.html.includes('Redefinir minha senha'));
    const url = new URL(message.text.split('\n\n').at(-1));
    assert.equal(url.origin, base); assert.equal(url.pathname, '/redefinir-senha');
    return { token: new URLSearchParams(url.hash.slice(1)).get('token'), response };
  };
  const first = await issue();
  const record = await prisma.passwordResetToken.findUniqueOrThrow({ where: { tokenHash: hash(first.token) } });
  assert.match(first.token, /^[A-Za-z0-9_-]{43}$/);
  assert.ok(!JSON.stringify(record).includes(first.token));
  assert.ok(record.expiresAt > new Date() && record.expiresAt <= new Date(Date.now() + 1800000));
  const before = mail.length;
  const unknown = await request(randomUUID() + '@example.test');
  assert.equal(unknown.status, first.response.status);
  assert.deepEqual(await unknown.json(), await first.response.json());
  await new Promise(r => setTimeout(r, 300)); assert.equal(mail.length, before);
  assert.equal(await prisma.passwordResetToken.count({ where: { userId: user.id } }), 1);
  assert.equal((await request('invalid')).status, 400);
  assert.equal((await reset('!'.repeat(43))).status, 400);
  assert.equal((await reset('z'.repeat(43))).status, 400);
  assert.equal((await reset(first.token, 'weak')).status, 400);
  assert.equal((await reset(first.token, nextPassword, password)).status, 400);
  const second = await issue(); assert.notEqual(second.token, first.token);
  assert.equal((await reset(first.token)).status, 400);
  await prisma.passwordResetToken.update({ where: { tokenHash: hash(second.token) }, data: { expiresAt: new Date(0) } });
  assert.equal((await reset(second.token)).status, 400);
  const third = await issue();
  await prisma.passwordResetToken.update({ where: { tokenHash: hash(third.token) }, data: { usedAt: new Date() } });
  assert.equal((await reset(third.token)).status, 400);
  const fourth = await issue();
  const race = await Promise.all([reset(fourth.token), reset(fourth.token)]);
  assert.deepEqual(race.map(r => r.status).sort(), [200, 400]);
  assert.equal((await reset(fourth.token)).status, 400);
  assert.ok((await prisma.passwordResetToken.findUniqueOrThrow({ where: { tokenHash: hash(fourth.token) } })).usedAt);
  assert.equal(await prisma.session.count({ where: { userId: user.id } }), 0);
  assert.equal((await current(cookie)).user, null);
  assert.equal((await login(nextPassword)).status, 200);
  assert.equal((await login(password)).status, 401);
  delivery.mode = 'fail';
  const failure = await issue();
  await waitFor(async () => await prisma.passwordResetToken.count({ where: { tokenHash: hash(failure.token) } }) === 0);
  assert.equal((await reset(failure.token)).status, 400);
  assert.equal(mail.at(-1).idempotencyKey, mail.at(-2).idempotencyKey);
  delivery.mode = 'ok';
  await clearLimits();
  const repeatedAddress = randomUUID() + '@example.test';
  for (let i = 0; i < 6; i++) assert.equal((await request(repeatedAddress)).status, 202, 'no email cooldown or hourly lockout');
  assert.equal((await request(randomUUID() + '@example.test')).status, 202, 'no request count lockout');
  for (let i = 0; i < 21; i++) assert.equal((await reset('z'.repeat(43))).status, 400, 'invalid token remains rejected without count lockout');
  assert.equal((await fetch(base + '/redefinir-senha')).status, 200);
  await clearLimits();
  console.log('PASS: password recovery, generic response, SDK delivery, hashed tokens, expiry/use/replay/race, password validation, session revocation, old/new login and no attempt lockout.');
}
